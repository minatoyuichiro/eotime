"""Build the arXiv submission package: paper/arxiv/main.tex with every generated table inlined
(arXiv's pdflatex cannot read \\@@input inside REVTeX tabulars), plus main.bbl, refs.bib and figs/.
Writes paper/eotime_arxiv_source.tar.gz.  Run after the PDF has been built (main.bbl must exist)."""
import os, re, tarfile, shutil, subprocess
B = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'paper'); B = os.path.abspath(B)
A = os.path.join(B, 'arxiv'); shutil.rmtree(A, ignore_errors=True); os.makedirs(os.path.join(A, 'figs'))
s = open(os.path.join(B, 'main.tex')).read()
s = s.replace('\\input{tables/macros}', open(os.path.join(B, 'tables', 'macros.tex')).read().rstrip('\n'))
s = re.sub(r'\\inputtable\{(tables/[\w]+\.tex)\}', lambda m: open(os.path.join(B, m.group(1))).read().rstrip('\n'), s)
s = re.sub(r'\\makeatletter\s*\\newcommand\{\\inputtable\}\[1\]\{\\@@input #1 \}\s*\\makeatother\s*', '', s)
HDR = '% arXiv submission file generated by code/make_arxiv.py: the numeric tables are inlined.\n% The editable source with the table inclusion macro and the generated table files is paper/main.tex in the repository.\n'
s = re.sub(r'\A(%[^\n]*\n)+', lambda m: HDR, s)
assert '\\inputtable' not in s and 'tables/' not in s, 'table inclusion left'
open(os.path.join(A, 'main.tex'), 'w').write(s)
for f in ['main.bbl', 'refs.bib']:
    shutil.copy(os.path.join(B, f), A)
for f in sorted(os.listdir(os.path.join(B, 'figs'))):
    if f.endswith('.png') and f'figs/{f[:-4]}' in s:
        shutil.copy(os.path.join(B, 'figs', f), os.path.join(A, 'figs', f))
with tarfile.open(os.path.join(B, 'eotime_arxiv_source.tar.gz'), 'w:gz') as t:
    for root, _, files in os.walk(A):
        for f in sorted(files):
            p = os.path.join(root, f); t.add(p, arcname=os.path.relpath(p, A))
print('arxiv package:', sorted(os.path.relpath(os.path.join(r, f), A) for r, _, fs in os.walk(A) for f in fs))
